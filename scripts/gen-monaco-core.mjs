// Regenerates src/editor/monaco.core.ts from Monaco's own entry point.
//
// monaco-editor/esm/vs/editor/editor.main.js pulls in every editor feature AND
// ~80 language grammars. We want the features and only the JSON language, but
// hand-maintaining the feature list rots across upgrades. So we derive it:
// take Monaco's list, drop the language registrations, keep everything else.
//
// Run with: node scripts/gen-monaco-core.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const ENTRY = 'node_modules/monaco-editor/esm/vs/editor/editor.main.js'
const TARGET = 'src/editor/monaco.core.ts'
const BASE = 'monaco-editor/esm/vs/editor/'

const header = `// GENERATED by scripts/gen-monaco-core.mjs — do not edit by hand.
//
// Monaco's full entry point registers ~80 language grammars we never use. This
// is the same editor feature set with those dropped; the JSON language is
// registered separately in monaco.ts. Re-run the script after upgrading
// monaco-editor.
`

const specifiers = readFileSync(ENTRY, 'utf8')
  .split('\n')
  // Side-effect imports only: the named/namespace ones are re-exports we take
  // from editor.api directly.
  .map((line) => line.match(/^import '(.*)';$/)?.[1])
  .filter((path) => path && !path.includes('languages/definitions/'))
  .map((path) => new URL(path, `file:///${BASE}`).pathname.replace(/^\//, ''))

writeFileSync(TARGET, `${header}\n${specifiers.map((s) => `import '${s}'`).join('\n')}\n`)
console.log(`${TARGET}: ${specifiers.length} imports`)
